        <h1>Om Mafioso</h1>
        <p>Mafioso er et tekstbasert mafiaspill hvor man spiller et rollespill. Alt som er i spillet er fiktivt og skal på ingen måte bli inspirert til å brukes eller konstrueres i det virkelige liv. Mafioso skal i hovedtrekk brukes som et tidsfordriv og en samleplass for venner. Spillet anbefales for ungdom over 16 år.</p>
        <br>
        <h2>Regler</h2>
        <p>For at det skal bli rettferdighet og ikke oppnå mistanke om juks er det derfor satt grense på max 1 bruker pr person. Dette må følges ellers blir din bruker deaktivert. Har du mistanke om at noen jukser eller bruker programmer som jukser på spillet skal dette raporteres til nærmeste administrator.<br>Personlig informasjon skal ikke deles videre blant medspillere. Er det mistanke om mobbing eller trakasering vil det bli gitt en form for straff, enten forum ban eller utestenging fra selve spillet. <br>
        Bruker du samme IP som andre spillere inne på spillet skal dette stå oppført på din profil. Spiller du på offentlige nett som skole, jobb osv. skal dette også stå oppført på din profil innen 7 dager. Du kan også kontake Skitzo for å avklare at det går greit å ha samme IP.</p>
        <br>
        <h2>Misbruk av funksjoner</h2>
        <p>Om det oppdages feil av funksjoner skal disse raporteres til nærmeste administrator / moderator. Ved misbruk av funksjoner så vil det bli gitt en form for straff, enten det er bann fra spillet eller reduserte goder.</p>
        <br>
        <h2>Handel av verdier utenfor mafioso.no</h2>
        <p>Om du selger verdier fra mafioso.no for penger utenfor mafioso.no så telles dette som juks og kan i verste fall føre til utestengelse av spillet.</p>
        <br>
        <h2>Innsamlinger av data</h2>
        <p>Ved å registrere deg på Mafioso.no så godtar du at vi samler inn data som b.la e-post addressen og din IP-addresse. Ved å samle inn brukernes IP-addresse har vi mulighet for å oppdage juks, det blir ikke brukt av noen andre formål. Din data blir lagret trygt i vår database og deles ikke med noen. Om du ønsker innsyn i dine data så send en mail til post@mafioso.no</p>
